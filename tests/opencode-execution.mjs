import assert from 'node:assert/strict';
import { inspectExecution, requestExecutionCancel } from '../worker/opencode-execution.mjs';
const record = { openCodeSessionId: 's', userMessageId: 'current', directory: '/mock', requestStarted: true };
let status = { s: { type: 'busy' } }, messages = [{ info: { id: 'current', role: 'user' } }], abort = false;
const api = async path => path === '/session/status' ? status : path.endsWith('/abort') ? abort : messages;
assert.equal((await inspectExecution(api, record)).state, 'RUNNING');
await requestExecutionCancel(api, record);
assert.equal(record.abortAcknowledged, false);
status = {};
assert.equal((await inspectExecution(api, record)).state, 'UNKNOWN', 'idle without acknowledgement is not cancelled');
messages.push({ info: { role: 'assistant', parentID: 'previous', finish: 'stop', time: { completed: 1 } }, parts: [{ type: 'text', text: 'old' }] });
assert.equal((await inspectExecution(api, record)).state, 'UNKNOWN', 'old answer must not satisfy current request');
abort = true; await requestExecutionCancel(api, record);
assert.equal((await inspectExecution(api, record)).state, 'CANCELLED');
messages.push({ info: { role: 'assistant', parentID: 'current', finish: 'stop', time: { completed: 1 } }, parts: [{ type: 'text', text: 'actual result' }] });
assert.equal((await inspectExecution(api, record)).state, 'COMPLETED', 'completed execution wins a cancellation race');
messages = [];
assert.equal((await inspectExecution(api, record)).state, 'UNKNOWN', 'an unobserved user message must not be cancelled or completed');
console.log('Execution evidence, abort acknowledgement and turn-specific result matching passed');
